# ------------------------------------------------------------------------------
def parse_admins(admins_str):
    admins = []
    if admins_str:
        for admin in admins_str.split(','):
            try:
                name, email = admin.split(':')
                admins.append((name.strip(), email.strip()))
            except ValueError:
                raise ValueError(f"Incorrect admin format: {admin}. Waiting for - 'имя:email'.")
    return admins

